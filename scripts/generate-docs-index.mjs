// Writes website/src/docs_index.ml from the `docs` registry in
// website/docs.pages.mjs: the page records the site's sidebar, routes and
// previous/next links are built from.
//
//   node scripts/generate-docs-index.mjs           write the file
//   node scripts/generate-docs-index.mjs --check   fail if it is out of date
//
// Each page's `body` names the OCaml function that renders it, so a page
// registered without one is a compile error, not a blank page.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { docs, pages as agentPages } from "../website/docs.pages.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "website", "src", "docs_index.ml");
const agentSlugs = new Set(agentPages.map((p) => p.slug));

const fail = (message) => {
  console.error(`generate-docs-index: ${message}`);
  process.exit(1);
};

// Melange reads a plain string literal byte by byte, so text goes out as a
// {js|...|js} literal; keep it ASCII and free of backslashes all the same.
const str = (s, where) => {
  if (typeof s !== "string" || s.length === 0) fail(`${where}: missing text`);
  if (/[^\x20-\x7e]/.test(s)) fail(`${where}: use plain ASCII (${JSON.stringify(s)})`);
  if (s.includes("\\") || s.includes("|js}")) fail(`${where}: no backslashes`);
  return `{js|${s}|js}`;
};

const seen = new Set();
const lines = [
  "(* Generated by scripts/generate-docs-index.mjs from website/docs.pages.mjs.",
  "   Do not edit: change the registry, then run the script. *)",
  "",
  "type page = {",
  "  title : string;",
  "  heading : string;",
  "  path : string;",
  "  section : string;",
  "  lead : string;",
  "  agent : string option;",
  "  is_new : bool;",
  "  body : unit -> Doc.block list;",
  "}",
  "",
  "let sections : (string * page list) list =",
  "  [",
];
for (const section of docs) {
  lines.push(`    ( ${str(section.label, "section")},`, "      [");
  for (const page of section.pages) {
    const where = page.path ?? section.label;
    if (!/^\/docs(\/[a-z0-9-]+)*$/.test(page.path ?? "")) fail(`${where}: bad path`);
    if (seen.has(page.path)) fail(`${where}: duplicate path`);
    seen.add(page.path);
    if (!/^[A-Z][A-Za-z0-9_]*\.[a-z_][A-Za-z0-9_']*$/.test(page.body ?? "")) fail(`${where}: body must be Module.name`);
    if (page.agent && !agentSlugs.has(page.agent)) fail(`${where}: unknown agent page ${page.agent}`);
    lines.push(
      "        {",
      `          title = ${str(page.title, where)};`,
      `          heading = ${str(page.heading ?? page.title, where)};`,
      `          path = ${str(page.path, where)};`,
      `          section = ${str(section.label, where)};`,
      `          lead = ${str(page.lead, where)};`,
      `          agent = ${page.agent ? `Some ${str(page.agent, where)}` : "None"};`,
      `          is_new = ${page.isNew ? "true" : "false"};`,
      `          body = ${page.body};`,
      "        };",
    );
  }
  lines.push("      ] );");
}
lines.push(
  "  ]",
  "",
  "let pages = List.concat_map snd sections",
  "let find path = List.find_opt (fun page -> String.equal page.path path) pages",
  "",
);
const output = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== output) fail("website/src/docs_index.ml is out of date; run node scripts/generate-docs-index.mjs");
  console.log("docs_index.ml is up to date");
} else {
  writeFileSync(target, output);
  console.log(`wrote ${target}`);
}
